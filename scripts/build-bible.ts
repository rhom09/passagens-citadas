// Script build-bible: lê arc.source.json e gera contagens + loader + search-index.v1.json

import fs from 'fs';
import path from 'path';
import { normalize } from '../src/lib/detect/normalize';
import { PORTUGUESE_STOPWORDS } from '../src/lib/search/constants';
import type { VerseIndexDoc, SearchIndexData } from '../src/lib/search/types';

interface ArcBook {
  abbrev: string;
  name: string;
  chapters: string[][];
}

interface ArcData {
  books: ArcBook[];
}

// Lê dados da ARC
const arcDataPath = path.resolve(process.cwd(), 'data', 'arc.source.json');
const rawData = JSON.parse(fs.readFileSync(arcDataPath, 'utf-8')) as ArcBook[] | ArcData;
const arcData: ArcData = Array.isArray(rawData) ? { books: rawData } : rawData;

// Verifica 66 livros
if (arcData.books.length !== 66) {
  console.error(`⚠️ Esperados 66 livros, encontrados: ${arcData.books.length}`);
  process.exit(1);
}

// Conta capítulos totais
const totalCapitulos = arcData.books.reduce((sum, book) => sum + book.chapters.length, 0);
console.log(`✓ 66 livros encontrados`);
console.log(`✓ Total de capítulos: ${totalCapitulos}`);

// Conta versículos por capítulo
const verseCounts: number[][] = arcData.books.map((book) =>
  book.chapters.map((chapter) => chapter.length)
);

// Verifica casos conhecidos
const salmosIdx = arcData.books.findIndex(
  (b) => b.abbrev === 'PSA' || b.name.toLowerCase().includes('salmo')
);
if (salmosIdx >= 0) {
  const salmosVersiculos = verseCounts[salmosIdx].reduce((sum, v) => sum + v, 0);
  console.log(`✓ Salmos: ${salmosVersiculos} versículos (${verseCounts[salmosIdx].length} capítulos)`);
}

// Verifica Números 2
const numerosIdx = arcData.books.findIndex((b) => b.abbrev === 'NUM');
if (numerosIdx >= 0) {
  const numeros2Cap = arcData.books[numerosIdx].chapters[1]; // capítulo 2
  const numeros2Vers = numeros2Cap ? numeros2Cap.length : 0;
  console.log(`✓ Números 2: ${numeros2Vers} versículos`);
}

// Verifica João
const joaoIdx = arcData.books.findIndex((b) => b.abbrev === 'JHN');
if (joaoIdx >= 0) {
  const joaoCap = arcData.books[joaoIdx].chapters.length;
  const joao3Vers = verseCounts[joaoIdx][2] || 0; // capítulo 3
  console.log(`✓ João: ${joaoCap} capítulos, cap 3: ${joao3Vers} versículos`);
}

// Gera VERSE_COUNTS export
const verseCountsExport = `export const VERSE_COUNTS: readonly (readonly number[])[] = ${JSON.stringify(
  verseCounts,
  null,
  2
)} as const;`;

// Gera counts.ts
const countsContent = `// Auto-generated by scripts/build-bible.ts
${verseCountsExport}

// Função para contar versículos de um capítulo de um livro
export function verseCount(bookId: number, chapter: number): number | undefined {
  const chapters = VERSE_COUNTS[bookId - 1];
  if (!chapters || chapter < 1 || chapter > chapters.length) {
    return undefined;
  }
  return chapters[chapter - 1];
}

// Função para contar capítulos de um livro
export function chapterCount(bookId: number): number | undefined {
  const chapters = VERSE_COUNTS[bookId - 1];
  if (!chapters) {
    return undefined;
  }
  return chapters.length;
}
`;

// Gera loader.ts
const loaderContent = `// Auto-generated by scripts/build-bible.ts
import type { Bible } from './types';

let cachedBible: Bible | null = null;
let loadingPromise: Promise<Bible> | null = null;

interface RawArcBook {
  id?: number;
  abbrev?: string;
  name: string;
  chapters: string[][];
}

function normalizeBibleData(raw: unknown): Bible {
  const rawBooks: RawArcBook[] = Array.isArray(raw)
    ? (raw as RawArcBook[])
    : ((raw as { books?: RawArcBook[] })?.books ?? []);

  return {
    version: 'ARC',
    books: rawBooks.map((book, idx) => ({
      id: book.id ?? idx + 1,
      name: book.name,
      chapters: book.chapters,
    })),
  };
}

export async function loadBible(): Promise<Bible> {
  if (cachedBible) return cachedBible;
  if (!loadingPromise) {
    loadingPromise = fetch('/data/arc.v1.json')
      .then((res) => {
        if (!res.ok) {
          throw new Error(\`Falha ao carregar /data/arc.v1.json (\${res.status})\`);
        }
        return res.json();
      })
      .then((data) => {
        cachedBible = normalizeBibleData(data);
        return cachedBible;
      })
      .catch((err) => {
        loadingPromise = null;
        throw err;
      });
  }
  return loadingPromise;
}

export function getVerse(bible: Bible, bookId: number, ch: number, v: number): string | undefined {
  const book = bible.books[bookId - 1];
  if (!book) return undefined;

  const chapter = book.chapters[ch - 1];
  if (!chapter) return undefined;

  if (v < 1 || v > chapter.length) return undefined;

  return chapter[v - 1];
}

export function getPassageText(
  bible: Bible,
  passage: { bookId: number; chapter: number; verseStart?: number; verseEnd?: number }
): string | undefined {
  const { bookId, chapter, verseStart, verseEnd } = passage;

  if (verseStart === undefined) {
    const book = bible.books[bookId - 1];
    const ch = book?.chapters[chapter - 1];
    if (!ch || ch.length === 0) return undefined;
    return ch.map((text, idx) => \`\${idx + 1} \${text}\`).join(' ');
  }

  const end = verseEnd !== undefined && verseEnd > verseStart ? verseEnd : verseStart;
  const parts: string[] = [];

  for (let v = verseStart; v <= end; v++) {
    const text = getVerse(bible, bookId, chapter, v);
    if (text) {
      parts.push(end > verseStart ? \`\${v} \${text}\` : text);
    }
  }

  return parts.length > 0 ? parts.join(' ') : undefined;
}
`;

// Escreve arquivos de código
const libBiblePath = path.resolve(process.cwd(), 'src', 'lib', 'bible');
const countsPath = path.join(libBiblePath, 'counts.ts');
const loaderPath = path.join(libBiblePath, 'loader.ts');
const arcV1Path = path.resolve(process.cwd(), 'public', 'data', 'arc.v1.json');
const searchIndexPath = path.resolve(process.cwd(), 'public', 'data', 'search-index.v1.json');

fs.writeFileSync(countsPath, countsContent);
console.log(`✓ Gerado: ${countsPath}`);

fs.writeFileSync(loaderPath, loaderContent);
console.log(`✓ Gerado: ${loaderPath}`);

if (!fs.existsSync(path.join(process.cwd(), 'public'))) {
  fs.mkdirSync(path.join(process.cwd(), 'public'), { recursive: true });
}
if (!fs.existsSync(path.join(process.cwd(), 'public', 'data'))) {
  fs.mkdirSync(path.join(process.cwd(), 'public', 'data'), { recursive: true });
}
fs.writeFileSync(arcV1Path, JSON.stringify(arcData, null, 2));
console.log(`✓ Gerado: ${arcV1Path}`);

// ── Gerar Search Index BM25 (public/data/search-index.v1.json) ───────────────
console.log('Construindo índice de busca BM25...');

const verses: VerseIndexDoc[] = [];
const invertedIndex: Record<string, [number, number][]> = {};
let totalDocLen = 0;

let docIdx = 0;
arcData.books.forEach((book, bIdx) => {
  const bookId = bIdx + 1;
  book.chapters.forEach((chapter, cIdx) => {
    const chNum = cIdx + 1;
    chapter.forEach((verseText, vIdx) => {
      const vNum = vIdx + 1;
      const normText = normalize(verseText);
      const tokens = normText.split(/\s+/).filter(Boolean);

      // Filtrar stopwords e palavras muito curtas (1 caractere)
      const contentTokens = tokens.filter(
        (t) => t.length > 1 && !PORTUGUESE_STOPWORDS.has(t)
      );

      const docLen = contentTokens.length;
      totalDocLen += docLen;

      verses.push({
        bookId,
        chapter: chNum,
        verse: vNum,
        text: verseText,
        len: docLen,
      });

      // Contagem de frequência de termos no documento
      const tfMap: Record<string, number> = {};
      for (const t of contentTokens) {
        tfMap[t] = (tfMap[t] || 0) + 1;
      }

      for (const [term, tf] of Object.entries(tfMap)) {
        if (!invertedIndex[term]) {
          invertedIndex[term] = [];
        }
        invertedIndex[term].push([docIdx, tf]);
      }

      docIdx++;
    });
  });
});

const docCount = verses.length;
const avgDocLen = docCount > 0 ? totalDocLen / docCount : 0;

// Calcular IDF para cada termo: ln(1 + (N - n + 0.5) / (n + 0.5))
const idf: Record<string, number> = {};
for (const [term, postings] of Object.entries(invertedIndex)) {
  const n = postings.length;
  idf[term] = Math.log(1 + (docCount - n + 0.5) / (n + 0.5));
}

const searchIndexData: SearchIndexData = {
  version: '1.0',
  docCount,
  avgDocLen,
  verses,
  invertedIndex,
  idf,
};

fs.writeFileSync(searchIndexPath, JSON.stringify(searchIndexData));
const indexSizeMb = (fs.statSync(searchIndexPath).size / (1024 * 1024)).toFixed(2);
console.log(`✓ Gerado: ${searchIndexPath} (${indexSizeMb} MB, ${docCount} versículos, ${Object.keys(invertedIndex).length} termos únicos)`);

console.log('\n=== Build Bible Report ===');
console.log('Script concluído com sucesso!');
